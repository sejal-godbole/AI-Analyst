"""
LLM-as-a-Judge Evaluator for LLM #3 (Final Answer / Natural Language Generation).
Uses Gemini Flash with a dedicated strict evaluation prompt.
"""
from __future__ import annotations

import json
import logging
import re
from typing import Optional
from openai import OpenAI

from app.config import get_settings
from app.evaluation.models import FinalAnswerEvaluationResult, GoldenTestCase

logger = logging.getLogger("ai_analyst.evaluation.judge")

_JSON_EXTRACT_RE = re.compile(r"\{.*\}", re.DOTALL)

JUDGE_SYSTEM_PROMPT = """You are an expert, strict LLM Judge evaluating the final natural language answer generated by a database AI assistant.

Evaluate the generated answer against:
1. The User's Question
2. The Actual Database Result (or Error/Redaction status)
3. Expected Behavior / Reference Answer (if provided)

SECURITY & PII REDACTION POLICY:
The assistant enforces an automated PII/Security Guardrail: sensitive columns (such as email, phone, password, salary, ssn, credit_card) are automatically filtered and redacted from query results before generating the final answer.
- If the generated answer explains that sensitive columns (e.g. email) were redacted or withheld for security/PII reasons, this is DESIRED, ACCURATE, and GROUNDED security behavior—do NOT consider it a hallucination or error.
- The assistant is expected to summarize key entities (names, cities, counts) without needing to list every internal database ID unless specifically requested.

Score each criterion strictly on a scale of 0 to 10 (where 10 is perfect and 0 is completely unacceptable):

- Relevance (0-10): Does the answer directly address the user's core question without deviating?
- Correctness (0-10): Is the answer factually consistent with the database result and security policies?
- Groundedness (0-10): Does the answer contain ONLY claims supported by the database return and security rules? Strictly penalize any fabricated numbers or entities.
- Completeness (0-10): Does the answer provide all information necessary to satisfy the user's inquiry (accounting for PII filtering)?
- Clarity (0-10): Is the response concise, clear, and well-structured?

You MUST respond with a single valid JSON object ONLY. Do NOT include markdown fences, backticks, or preamble.
Example JSON:
{
  "relevance": 10,
  "correctness": 10,
  "groundedness": 10,
  "completeness": 10,
  "clarity": 10,
  "reason": "The answer accurately lists the customer names and cities while properly adhering to PII redaction policies for email."
}
"""


def evaluate_final_answer(
    user_question: str,
    generated_answer: str,
    database_result: Optional[str] = None,
    golden_test_case: Optional[GoldenTestCase] = None,
    error: Optional[str] = None,
) -> FinalAnswerEvaluationResult:
    """
    Evaluates LLM #3 using LLM-as-a-Judge (Gemini Flash).
    Safe with fallback handling so it never crashes the application.
    """
    settings = get_settings()
    model_name = getattr(settings, "eval_judge_model", "gemini-3.1-pro-preview") or settings.llm_model
    judge_api_key = getattr(settings, "eval_judge_api_key", None) or settings.llm_api_key
    judge_base_url = getattr(settings, "eval_judge_base_url", None) or settings.llm_base_url

    # Build evaluation context
    user_prompt = f"""=== USER QUESTION ===
{user_question}

=== ACTUAL DATABASE RESULT / STATUS ===
{database_result or (f"Execution Error / Status: {error}" if error else "No raw rows returned.")}

=== EXPECTED BEHAVIOR / REFERENCE ANSWER ===
{golden_test_case.reference_answer if golden_test_case and golden_test_case.reference_answer else (golden_test_case.expected_behavior if golden_test_case else "Accurately summarize the database result for the user.")}

=== GENERATED FINAL ANSWER ===
{generated_answer or "No answer generated."}

Evaluate the generated answer now and return JSON:"""

    # Attempt LLM Judge call with rate-limit retry
    client = OpenAI(api_key=judge_api_key, base_url=judge_base_url)
    raw_text = ""
    for attempt in range(3):
        try:
            response = client.chat.completions.create(
                model=model_name,
                temperature=0.0,
                messages=[
                    {"role": "system", "content": JUDGE_SYSTEM_PROMPT},
                    {"role": "user", "content": user_prompt},
                ],
            )
            raw_text = (response.choices[0].message.content or "").strip()
            if raw_text:
                break
        except Exception as e:
            if "429" in str(e) and attempt < 2:
                import time
                time.sleep(2.5 * (attempt + 1))
                continue
            logger.warning("LLM-as-a-Judge evaluation attempt %d failed: %s", attempt + 1, e)
            break

    if raw_text:
        # Parse JSON
        parsed_json = None
        try:
            parsed_json = json.loads(raw_text)
        except json.JSONDecodeError:
            match = _JSON_EXTRACT_RE.search(raw_text)
            if match:
                try:
                    parsed_json = json.loads(match.group(0))
                except json.JSONDecodeError:
                    pass

        if parsed_json and isinstance(parsed_json, dict):
            rel = float(parsed_json.get("relevance", 8.0))
            corr = float(parsed_json.get("correctness", 8.0))
            grd = float(parsed_json.get("groundedness", 8.0))
            comp = float(parsed_json.get("completeness", 8.0))
            clar = float(parsed_json.get("clarity", 8.0))
            reason = str(parsed_json.get("reason", "LLM-as-a-Judge completed evaluation."))

            # Average score
            final_score = round((rel + corr + grd + comp + clar) / 5.0, 2)

            return FinalAnswerEvaluationResult(
                final_answer_score=final_score,
                relevance=rel,
                correctness=corr,
                groundedness=grd,
                completeness=comp,
                clarity=clar,
                reason=reason,
                judge_model=model_name,
                generated_answer=generated_answer,
            )

    # Fallback heuristic score if LLM judge API call is unreachable or fails
    has_content = bool(generated_answer and len(generated_answer.strip()) > 10)
    score = 8.0 if has_content else 4.0
    return FinalAnswerEvaluationResult(
        final_answer_score=score,
        relevance=score,
        correctness=score,
        groundedness=score,
        completeness=score,
        clarity=score,
        reason="Heuristic evaluation applied (Judge API offline or response unparsed).",
        judge_model="fallback_heuristic",
        generated_answer=generated_answer,
    )
